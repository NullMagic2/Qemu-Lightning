//! Module: lightning.direct3d12_umd.generate_queue_header
//! Purpose: Generate the private queue scalar ABI from its owning Rust schema.
//! Created: 2026-10-24
//! Architecture: This never defines a Vulkan ABI; official Vulkan types stay in C.
#[path = "queue.rs"]
pub mod queue;
use core::mem::size_of;
fn record(name: &str, bytes: usize, fields: impl FnOnce(&mut dyn FnMut(&str, &str, usize))) {
    let mut entries = Vec::new();
    fields(&mut |field, kind, offset| entries.push((field.to_string(), kind.to_string(), offset)));
    println!("typedef struct {name} {{");
    for (field, kind, _) in &entries {
        println!(
            "    {} {field};",
            if kind == "u64" {
                "uint64_t"
            } else {
                "uint32_t"
            }
        );
    }
    println!("}} {name};");
    println!("_Static_assert(sizeof({name}) == {bytes}, \"{name} size\");");
    for (field, _, offset) in &entries {
        println!("_Static_assert(offsetof({name}, {field}) == {offset}, \"{name}.{field}\");");
    }
}
fn main() {
    println!("/* Generated by generate_queue_header.rs from queue.rs; private scalar ABI. */");
    println!("#pragma once\n#include <stdint.h>\n#include <stddef.h>");
    for (name, value) in [
        ("VERSION", queue::COMMAND_VERSION),
        ("SIGNAL", queue::SIGNAL),
        ("QUERY", queue::QUERY),
        ("WAIT", queue::WAIT),
        ("SUCCESS", queue::SUCCESS),
        ("TIMEOUT", queue::TIMEOUT),
        ("FAILED", queue::FAILED),
        ("READY", queue::READY),
        ("FAULTED", queue::FAULTED),
    ] {
        println!("#define QLDX12_QUEUE_{name} UINT32_C({value})");
    }
    println!(
        "#define QLDX12_QUEUE_MAX_WAIT_NS UINT64_C({})",
        queue::MAX_WAIT_NS
    );
    record(
        "QLDX12_QUEUE_COMMAND",
        size_of::<queue::QueueCommand>(),
        |f| queue::visit_command(f),
    );
    record("QLDX12_QUEUE_PLAN", size_of::<queue::QueuePlan>(), |f| {
        queue::visit_plan(f)
    });
    record(
        "QLDX12_QUEUE_COMPLETION",
        size_of::<queue::QueueCompletion>(),
        |f| queue::visit_completion(f),
    );
    record(
        "QLDX12_QUEUE_REPORT",
        size_of::<queue::QueueReport>(),
        |f| queue::visit_report(f),
    );
}
