//! Module: lightning.guest_vulkan.generate_transport_header
//! Purpose: Generate the reviewed C ABI from the shared Rust Venus contract.
//! Created: 2026-10-09
//! Architecture: Used by Mesa Windows, the kernel Escape shim and host worker.
mod transport_contract;
use std::fmt::Write;
fn main() {
    let mut result = String::from("/* Generated by guest-vulkan/generate_transport_header.rs. */\n#ifndef QLV_TRANSPORT_H\n#define QLV_TRANSPORT_H\n#include <stdint.h>\n#include <stddef.h>\n");
    transport_contract::constants(|name, value| {
        writeln!(result, "#define QLV_{name} UINT64_C({value})").unwrap();
    });
    result.push_str("typedef struct QLV_HEADER {\n    uint32_t magic; uint16_t version; uint16_t operation;\n    uint64_t context; uint64_t resource; uint64_t value;\n    uint64_t bytes; uint64_t offset;\n    int32_t status; uint32_t flags; uint32_t payload_bytes; uint32_t reserved;\n} QLV_HEADER;\ntypedef struct QLV_SYNC_POINT { uint64_t sync; uint64_t value; } QLV_SYNC_POINT;\ntypedef struct QLV_CAPS {\n    uint32_t wire_format_version; uint32_t vk_xml_version;\n    uint32_t command_serialization_spec_version; uint32_t venus_protocol_spec_version;\n    uint32_t supports_blob_id_0; uint32_t extension_mask[QLV_EXTENSION_MASK_WORDS];\n    uint32_t allow_vk_wait_syncs; uint32_t supports_multiple_timelines; uint32_t use_guest_vram;\n} QLV_CAPS;\n#endif\n");
    // Refer to the exact schema so generator compilation checks its framing too.
    assert!(transport_contract::Header::request(transport_contract::OPEN, 0).valid_request(0));
    assert!(transport_contract::valid_operation(
        &transport_contract::Header::request(transport_contract::OPEN, 0)
    ));
    let header = transport_contract::Header::request(transport_contract::OPEN, 0);
    assert_eq!(
        transport_contract::Header::from_le_bytes(&header.to_le_bytes()),
        Some(header)
    );
    let point = transport_contract::SyncPoint::default();
    assert_eq!(
        transport_contract::SyncPoint::from_le_bytes(&point.to_le_bytes()),
        Some(point)
    );
    print!("{result}");
}
